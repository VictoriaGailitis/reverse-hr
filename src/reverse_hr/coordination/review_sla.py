"""Durable reminder, reviewer rotation and escalation for independent review.

Reviewers opt into a 15-minute MFA-authenticated availability lease. A worker
only proposes assignments after fresh permission/independence checks; the real
review endpoint still requires a fresh authenticated role and MFA. No outcomes
or sanctions are generated by the scheduler.
"""

from datetime import UTC, datetime, timedelta
from uuid import UUID, uuid4

from fastapi import APIRouter, HTTPException, Request, Response
from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from reverse_hr.contracts.events import EventEnvelope
from reverse_hr.shared.auth import Actor, Principal
from reverse_hr.shared.db import IdempotencyRecord, Outbox, enqueue


class AvailabilityPrincipal(Principal):
    """Internal scheduling proof, never constructed from an API request."""


def utc(value):
    return value.replace(tzinfo=UTC) if value.tzinfo is None else value.astimezone(UTC)


def subject_lock(session, service, subject, *, allow_blocked=False):
    if service == "assessment":
        from reverse_hr.services.assessment.domain.assessment_sessions import subject_lock as lock

        lock(session, subject)
    elif service == "employer":
        from reverse_hr.services.employer.domain.employer import subject_lock as lock

        lock(session, subject, allow_blocked=allow_blocked)
    else:
        from reverse_hr.protocols.market_state import lock
        from reverse_hr.services.hiring.domain.hiring import HiringSubject

        lock(session, HiringSubject, subject, allow_blocked=allow_blocked)


def cases(session, service):
    """Only live reviews. No terminal record can be reopened by scheduling."""
    if service == "assessment":
        from reverse_hr.services.assessment.domain.assessment_appeals import Appeal

        for row in session.scalars(
            select(Appeal)
            .where(Appeal.status.in_(["submitted", "in_review"]))
            .order_by(Appeal.appeal_id)
        ):
            yield "assessment_appeal", row, row.candidate_id, utc(row.review_due_at)
    elif service == "employer":
        from reverse_hr.services.employer.domain.employer_trust import TrustAppeal

        for row in session.scalars(
            select(TrustAppeal).where(TrustAppeal.status == "open").order_by(TrustAppeal.appeal_id)
        ):
            yield "trust_appeal", row, row.author_id, datetime.fromisoformat(row.data["due_at"])
    else:
        from reverse_hr.services.hiring.domain.hiring_dialogs import Complaint
        from reverse_hr.services.hiring.domain.hiring_moderation import ComplaintCase
        from reverse_hr.services.hiring.domain.hiring_trust import EmployerReview, ModerationAppeal

        for row in session.scalars(
            select(ModerationAppeal)
            .where(ModerationAppeal.status == "open")
            .order_by(ModerationAppeal.appeal_id)
        ):
            yield (
                "moderation_appeal",
                row,
                row.author_id,
                datetime.fromisoformat(row.data["due_at"]),
            )
        for row in session.scalars(
            select(EmployerReview)
            .where(EmployerReview.status == "pending")
            .order_by(EmployerReview.review_id)
        ):
            yield (
                "employer_review",
                row,
                row.author_id,
                datetime.fromisoformat(row.data["created_at"]) + timedelta(days=14),
            )
        for row in session.scalars(
            select(ComplaintCase)
            .where(ComplaintCase.status == "open")
            .order_by(ComplaintCase.complaint_id)
        ):
            complaint = session.get(Complaint, row.complaint_id)
            if complaint:
                yield (
                    "complaint",
                    row,
                    complaint.author_id,
                    utc(complaint.created_at) + timedelta(days=14),
                )


def identifier(kind, row):
    if kind == "employer_review":
        return row.review_id
    if kind == "complaint":
        return row.complaint_id
    return row.appeal_id


def fresh_guard(request, session, service, kind, row, actor):
    """Reuse real review access gates, including original author exclusions."""
    if kind == "assessment_appeal":
        from reverse_hr.services.assessment.domain.assessment_appeals import authorized

        authorized(request, session, actor, row, reviewer=True)
    elif kind == "trust_appeal":
        from reverse_hr.services.employer.domain.employer_trust import (
            Sanction,
            TrustDecision,
            independent,
            org_lock,
        )

        target = session.get(Sanction, row.target_id) or session.get(TrustDecision, row.target_id)
        if target is None:
            raise HTTPException(404)
        for subject in sorted({str(actor.subject), row.author_id, target.reviewer_id}):
            subject_lock(session, service, subject)
            request.app.state.processing_access.check(UUID(subject))
        independent(
            session, request, actor, UUID(row.organization_id), (row.author_id, target.reviewer_id)
        )
        org_lock(session, UUID(row.organization_id))
    elif kind == "moderation_appeal":
        from reverse_hr.services.hiring.domain.hiring_trust import appeal_guard

        appeal_guard(request, actor, session, row.appeal_id)
    elif kind == "employer_review":
        from reverse_hr.services.hiring.domain.hiring_trust import review_guard

        review_guard(request, actor, session, row.review_id, moderator=True)
    else:
        from reverse_hr.services.hiring.domain.hiring_moderation import guard_case

        guard_case(request, actor, session, row.complaint_id)


def participants(request, session, service, kind, row):
    if kind == "assessment_appeal":
        from reverse_hr.services.assessment.domain.assessment_appeals import (
            GradeDecision,
            PracticalSession,
            original_owners,
            policy_owners,
        )

        original = session.get(GradeDecision, row.decision_id)
        attempt = session.get(PracticalSession, row.session_id)
        if original is None or attempt is None:
            raise HTTPException(404)
        result = original_owners(original) | policy_owners(request, session, attempt)
    elif kind == "trust_appeal":
        from reverse_hr.services.employer.domain.employer_trust import Sanction, TrustDecision

        target = session.get(Sanction, row.target_id) or session.get(TrustDecision, row.target_id)
        result = {row.author_id} | ({target.reviewer_id} if target else set())
    elif kind == "complaint":
        from reverse_hr.services.hiring.domain.hiring_moderation import related

        result = related(session, row.complaint_id)[-1]
    else:
        from reverse_hr.services.hiring.domain.hiring import InvitationRow
        from reverse_hr.services.hiring.domain.hiring_moderation import related
        from reverse_hr.services.hiring.domain.hiring_trust import EmployerReview

        if kind == "moderation_appeal" and row.kind == "complaint":
            result = related(session, row.target_id)[-1] | {
                row.author_id,
                row.data["original_reviewer"],
            }
        else:
            review = (
                row if kind == "employer_review" else session.get(EmployerReview, row.target_id)
            )
            invitation = session.get(InvitationRow, review.invitation_id) if review else None
            if invitation is None:
                raise HTTPException(404)
            result = {invitation.candidate_id, invitation.created_by, review.author_id}
            if kind == "moderation_appeal":
                result |= {row.author_id, row.data["original_reviewer"]}
            if review.reviewer_id:
                result.add(review.reviewer_id)
    if getattr(row, "reviewer_id", None):
        result.add(row.reviewer_id)
    return result


def assignment_guard(session, service, kind, case_id, actor):
    """Call from human mutation endpoints; workers never bypass human MFA."""
    if isinstance(actor, AvailabilityPrincipal):
        return
    state = session.get(models_for(service)[1], (str(case_id), kind))
    if state:
        reviewer = state.data.get("reviewer_id")
        if reviewer and reviewer != str(actor.subject):
            raise HTTPException(403, "Review assigned to another independent reviewer")
        if str(actor.subject) in state.data.get("previous_reviewers", []):
            raise HTTPException(403, "Expired reviewer assignment")


def record(session, request, service, state, event, recipient, now):
    action_id = str(uuid4())
    Action = models_for(service)[2]
    session.add(
        Action(
            action_id=action_id,
            case_id=state.case_id,
            kind=state.kind,
            recipient_id=recipient,
            version=state.version,
            at=now,
            data={"event": event, "due_at": state.data["due_at"], "rule_version": "review-sla-v1"},
        )
    )
    enqueue(
        session,
        EventEnvelope(
            producer=service,
            event_type=service + ".review_sla_action.v1",
            correlation_id=request.state.trace_id,
            aggregate_id=UUID(action_id),
            aggregate_version=1,
            payload={
                "case_id": UUID(state.case_id),
                "action_id": UUID(action_id),
                "owner_id": UUID(state.owner_id),
            },
        ),
    )


def run_one(request, *, now=None):
    """One transactional action; row locks and persisted stages make retries safe."""
    now = now or datetime.now(UTC)
    service = request.app.state.settings.service_name
    Pool, State, _, role = models_for(service)
    with Session(request.app.state.engine) as session, session.begin():
        for kind, candidate, owner, due in cases(session, service):
            case_id = identifier(kind, candidate)
            # Participant locks serialize ledger creation with Privacy deletion.
            state = session.get(State, (case_id, kind))
            current = (state.data.get("reviewer_id") if state else None) or getattr(
                candidate, "reviewer_id", None
            )
            invalid_current = False
            try:
                for subject in sorted(
                    participants(request, session, service, kind, candidate)
                    | {owner}
                    | ({current} if current else set())
                ):
                    try:
                        subject_lock(session, service, subject)
                        request.app.state.processing_access.check(UUID(subject))
                    except HTTPException as exc:
                        if subject == current and exc.status_code in {403, 404, 409}:
                            invalid_current = True
                            continue
                        raise
            except HTTPException as exc:
                if exc.status_code in {403, 404, 409}:
                    continue
                raise
            session.refresh(candidate, with_for_update=True)
            # refresh after owner locks; concurrent terminal decisions take precedence.
            if candidate.status not in {"open", "pending", "submitted", "in_review"}:
                continue
            state = session.scalar(
                select(State)
                .where(State.case_id == case_id, State.kind == kind)
                .with_for_update()
                .execution_options(populate_existing=True)
            )
            current_after_lock = (state.data.get("reviewer_id") if state else None) or getattr(
                candidate, "reviewer_id", None
            )
            if current_after_lock != current:
                current = current_after_lock
                invalid_current = False
                if current:
                    try:
                        subject_lock(session, service, current)
                        request.app.state.processing_access.check(UUID(current))
                    except HTTPException as exc:
                        if exc.status_code in {403, 404, 409}:
                            invalid_current = True
                        else:
                            raise
            data = (
                dict(state.data) if state else {"due_at": due.isoformat(), "previous_reviewers": []}
            )
            stage = data.get("stage")
            event = None
            if now >= due + timedelta(days=2) and stage != "escalated":
                event = "escalated"
            elif now >= due and stage not in {"overdue", "escalated"}:
                event = "overdue"
            elif due - timedelta(days=1) <= now < due and stage is None:
                event = "reminder"
            if (
                event is None
                and state
                and (invalid_current or (not current and stage in {"overdue", "escalated"}))
            ):
                event = "assignment_recovered"
            if event is None:
                continue
            # Fresh-check all case participants using a currently available reviewer
            # before exposing the action; no pool means owner-only escalation inbox.
            pool = list(
                session.scalars(
                    select(Pool)
                    .where(Pool.available_until > now)
                    .order_by(Pool.subject_id)
                    .limit(100)
                )
            )
            previous = list(data.get("previous_reviewers", []))
            if event != "reminder" and current and current not in previous:
                previous.append(current)
            eligible = None
            if invalid_current and hasattr(candidate, "reviewer_id"):
                candidate.reviewer_id = None
                session.flush()
            for person in pool:
                if person.subject_id in previous:
                    continue
                actor = AvailabilityPrincipal(UUID(person.subject_id), frozenset({role}), True)
                try:
                    fresh_guard(request, session, service, kind, candidate, actor)
                except HTTPException as exc:
                    if exc.status_code in {403, 404, 409}:
                        continue
                    raise
                session.refresh(person, with_for_update=True)
                if utc(person.available_until) <= now:
                    continue
                eligible = person.subject_id
                break
            if event == "assignment_recovered" and eligible is None and not invalid_current:
                continue
            if state is None:
                state = State(
                    case_id=case_id,
                    kind=kind,
                    owner_id=owner,
                    version=candidate.version,
                    data=dict(data),
                )
                session.add(state)
            data.update(
                stage=stage if event == "assignment_recovered" else event,
                previous_reviewers=previous,
                subjects=sorted(
                    participants(request, session, service, kind, candidate)
                    | {owner}
                    | set(previous)
                ),
            )
            if event != "reminder":
                data["reviewer_id"] = eligible
                candidate.version += 1
                if hasattr(candidate, "reviewer_id"):
                    candidate.reviewer_id = eligible
                if kind == "assessment_appeal":
                    candidate.status = "in_review" if eligible else "submitted"
                    from reverse_hr.services.assessment.domain.assessment_appeals import action

                    action(
                        session,
                        request,
                        candidate,
                        AvailabilityPrincipal(UUID(eligible or owner), frozenset({role}), True),
                        "review_reassigned" if eligible else "reviewer_released",
                    )
                state.version = candidate.version
                record(
                    session,
                    request,
                    service,
                    state,
                    "reassigned" if eligible else "unassigned",
                    eligible,
                    now,
                )
            state.data = data
            record(session, request, service, state, event, eligible or current, now)
            session.flush()
            return True
    return False


def get_case(session, service, kind, case_id):
    for found_kind, row, _, _ in cases(session, service):
        if found_kind == kind and identifier(kind, row) == case_id:
            return row
    raise HTTPException(404)


def make_router(service):
    router = APIRouter(prefix="/v1/review-sla", tags=["review-sla"])
    Pool, State, Action, role = models_for(service)

    @router.put("/availability")
    def available(request: Request, actor: Actor, enabled: bool = True):
        actor.require(role, mfa=True)
        with Session(request.app.state.engine) as session, session.begin():
            subject_lock(session, service, actor.subject)
            request.app.state.processing_access.check(actor.subject)
            row = session.get(Pool, str(actor.subject))
            if row is None:
                row = Pool(subject_id=str(actor.subject), available_until=datetime.now(UTC))
                session.add(row)
            row.available_until = datetime.now(UTC) + timedelta(minutes=15 if enabled else 0)
            return {"available_until": row.available_until}

    @router.get(
        "/inbox",
        responses={
            200: {
                "headers": {
                    "X-HR-Next-Cursor": {
                        "description": "Next page UUID; advances past hidden actions",
                        "schema": {"type": "string", "format": "uuid"},
                    }
                }
            }
        },
    )
    def inbox(request: Request, response: Response, actor: Actor, after: UUID | None = None):
        actor.require(role, mfa=True)
        with Session(request.app.state.engine) as session, session.begin():
            subject_lock(session, service, actor.subject)
            request.app.state.processing_access.check(actor.subject)
            query = select(Action)
            if after:
                query = query.where(Action.action_id > str(after))
            scanned = list(session.scalars(query.order_by(Action.action_id).limit(51)))
            rows = scanned[:50]
            if len(scanned) > 50:
                response.headers["X-HR-Next-Cursor"] = rows[-1].action_id
            result = []
            for row in rows:
                try:
                    case = get_case(session, service, row.kind, row.case_id)
                    fresh_guard(request, session, service, row.kind, case, actor)
                    assignment_guard(session, service, row.kind, row.case_id, actor)
                except HTTPException as exc:
                    if exc.status_code in {403, 404, 409}:
                        continue
                    raise
                result.append(
                    {
                        "action_id": row.action_id,
                        "case_id": row.case_id,
                        "kind": row.kind,
                        "version": row.version,
                        "at": utc(row.at),
                        **row.data,
                    }
                )
            return result

    return router


def scrub(session, service, subject):
    Pool, State, Action, _ = models_for(service)
    states = list(session.scalars(select(State)))
    affected = [
        state
        for state in states
        if state.owner_id == subject
        or state.data.get("reviewer_id") == subject
        or subject in state.data.get("previous_reviewers", [])
        or subject in state.data.get("subjects", [])
    ]
    ids = [row.case_id for row in affected]
    actions = list(
        session.scalars(
            select(Action).where(Action.case_id.in_(ids) | (Action.recipient_id == subject))
        )
    )
    action_ids = [row.action_id for row in actions]
    session.execute(
        delete(Outbox).where(Outbox.envelope["aggregate_id"].as_string().in_(action_ids))
    )
    for case_id in ids:
        session.execute(
            delete(IdempotencyRecord).where(IdempotencyRecord.response.contains(case_id))
        )
    session.execute(delete(Action).where(Action.action_id.in_(action_ids)))
    for row in affected:
        session.delete(row)
    session.execute(delete(Pool).where(Pool.subject_id == subject))


def models_for(service):
    from importlib import import_module

    if service not in {"assessment", "employer", "hiring"}:
        raise ValueError("Unknown review owner")
    module = import_module("reverse_hr.services." + service + ".review_models")
    prefix = service.title()
    role = "assessment_reviewer" if service == "assessment" else "company_moderator"
    return (
        getattr(module, prefix + "Reviewer"),
        getattr(module, prefix + "SLA"),
        getattr(module, prefix + "Action"),
        role,
    )
